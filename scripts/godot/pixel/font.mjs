// Acentos (padrões de até 4 de largura): em cima (2 linhas) ou embaixo (cedilha).
const MARKS = {
  acute: ['..#', '.#.'], grave: ['#..', '.#.'], circ: ['.#.', '#.#'], tilde: ['.#.#', '#.#.'], diaeresis: ['#.#'],
};
