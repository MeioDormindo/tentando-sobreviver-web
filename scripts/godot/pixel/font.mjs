  à: ['a', 'grave'], á: ['a', 'acute'], â: ['a', 'circ'], ã: ['a', 'tilde'], ä: ['a', 'diaeresis'],
  è: ['e', 'grave'], é: ['e', 'acute'], ê: ['e', 'circ'], ë: ['e', 'diaeresis'],
